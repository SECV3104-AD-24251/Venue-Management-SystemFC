    document.addEventListener('DOMContentLoaded', () => {
      const roleCards = document.querySelectorAll('.role-card');
      roleCards.forEach(card => {
        card.addEventListener('click', () => {
          roleCards.forEach(c => {
            c.classList.remove('border-2', 'border-secondary', 'bg-primary/60');
            c.classList.add('border', 'border-white/10', 'bg-white/5');
            const ind = c.querySelector('.checkmark-indicator');
            ind.classList.remove('border-secondary', 'bg-secondary');
            ind.classList.add('border-slate-400');
            ind.querySelector('.material-symbols-outlined').classList.add('opacity-0');
            const heading = c.querySelector('h3, span.font-headline-sm');
            if (heading) {
              heading.classList.remove('text-white');
              heading.classList.add('text-slate-200');
            }
          });

          card.classList.remove('border', 'border-white/10', 'bg-white/5');
          card.classList.add('border-2', 'border-secondary', 'bg-primary/60');
          const activeInd = card.querySelector('.checkmark-indicator');
          activeInd.classList.remove('border-slate-400');
          activeInd.classList.add('border-secondary', 'bg-secondary');
          activeInd.querySelector('.material-symbols-outlined').classList.remove('opacity-0');
          const activeHeading = card.querySelector('h3, span.font-headline-sm');
          if (activeHeading) {
            activeHeading.classList.remove('text-slate-200');
            activeHeading.classList.add('text-white');
